#!/usr/bin/env python3
"""Check embedded art/audio and regenerate their provenance manifest."""
import array
import hashlib
import json
import math
from pathlib import Path
import wave
from PIL import Image

root = Path(__file__).resolve().parents[1]
assets = root / 'assets'
entries = []
art = ['fractured-moon', 'solar-forge', 'glass-cathedral', 'interceptor',
       'enemy-scout', 'enemy-weaver', 'enemy-lancer', 'enemy-carrier', 'enemy-turret',
       'boss-sentinel', 'boss-solstice', 'boss-choir']
for name in art:
    path = assets / (name + '.png')
    with Image.open(path) as im:
        info = dict(width=im.width, height=im.height, mode=im.mode)
        if name not in art[:3]:
            assert im.mode == 'RGBA', path
            alpha = im.getchannel('A')
            assert alpha.getextrema()[0] == 0 and alpha.getextrema()[1] >= 250, path
            corners = [(0, 0), (im.width-1, 0), (0, im.height-1), (im.width-1, im.height-1)]
            assert all(alpha.getpixel(c) <= 1 for c in corners), path
            info['transparent_corners'] = True
    entries.append(dict(file=str(path.relative_to(assets)), origin='Original image generated for Astra Fracture with OpenAI imagegen; no ROM assets', **info))
tracks = sorted((assets / 'audio').glob('*.wav'))
assert len(tracks) == 18
for path in tracks:
    with wave.open(str(path)) as wav:
        assert (wav.getnchannels(), wav.getsampwidth(), wav.getframerate()) == (2, 2, 44100), path
        samples = array.array('h', wav.readframes(wav.getnframes()))
        peak = max(abs(s) for s in samples)
        rms = math.sqrt(sum(float(s)*s for s in samples)/len(samples))
        assert 50 < peak < 32767 and rms > 5, path
        entries.append(dict(file=str(path.relative_to(assets)), origin='Original composition and PCM synthesis in src/audio.rs; no external samples', frames=wav.getnframes(), seconds=round(wav.getnframes()/44100, 3), channels=2, sample_rate=44100, peak=peak, rms=round(rms, 2)))
for name in ['Rajdhani-SemiBold.ttf', 'ShareTechMono-Regular.ttf', 'OFL-Rajdhani.txt', 'OFL-ShareTechMono.txt']:
    entries.append(dict(file=name, origin='Google Fonts; SIL Open Font License 1.1; see adjacent OFL text'))
entries.append(dict(file='app-icon.png', origin='Original procedural monogram generated by tools/make_icon.py'))
for e in entries:
    p = assets / e['file']
    e.update(bytes=p.stat().st_size, sha256=hashlib.sha256(p.read_bytes()).hexdigest())
assert not list(assets.rglob('*.rom')) and not list(assets.rglob('*.dsk'))
(assets / 'manifest.json').write_text(json.dumps(dict(project='Astra Fracture', version='0.1.2', assets=entries), indent=2, ensure_ascii=False)+'\n')
print(f'PASS: {len(art)} original images, 9 transparent sprites, 18 stereo WAV, fonts and icon; SHA-256 manifest written.')
